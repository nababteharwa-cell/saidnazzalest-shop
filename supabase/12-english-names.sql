-- Owner: change one item's English name from the stock app.
-- The shop product follows, unless its English name was changed by hand in the shop panel.
create or replace function public.inv_item_name_en(item bigint, en text)
returns void language plpgsql security definer set search_path = public as $$
declare it public.inv_items; nv text := nullif(trim(en), '');
begin
  if public.inv_role() is distinct from 'owner' then raise exception 'owner_only'; end if;
  if length(coalesce(nv, '')) > 200 then raise exception 'too_long'; end if;
  select * into it from inv_items where id = item for update;
  if it.id is null then raise exception 'no_item'; end if;
  update inv_items set name_en = nv, updated_at = now() where id = item;
  perform set_config('hist.src', 'تطبيق المخزون', true);
  update products set data = jsonb_set(data, '{name_en}', to_jsonb(coalesce(nv, ''))), updated_at = now()
   where id = 't' || it.code and coalesce(data->>'name_en', '') in ('', coalesce(it.name_en, ''));
end $$;
revoke all on function public.inv_item_name_en(bigint, text) from public, anon;
grant execute on function public.inv_item_name_en(bigint, text) to authenticated;
